function humorFor(category, absurdity, controversy) {
  if (controversy >= 2 || absurdity >= 5) return 'dark_light';
  if (absurdity >= 3 || ['awkward', 'abstract', 'celebrities'].includes(category)) {
    return 'quirky';
  }
  return 'family';
}

