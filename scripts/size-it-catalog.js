/**
 * Catalogue Size It — tailles documentées (convention de jeu).
 * Utilisé par scripts/build-size-it-bank.js
 *
 * trueSize + unit + dimension = vérité métier.
 * shape = famille de silhouette procédurale (CC0, générée).
 */
'use strict';

function slug(s) {
  return String(s)
    .normalize('NFD')
    .replace(/[\u0300-\u036f]/g, '')
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/^-|-$/g, '');
}

function item(category, name, trueSize, unit, dimension, shape, method) {
  return {
    id: `${category.slice(0, 4)}-${slug(name)}`,
    name,
    category,
    dimension,
    trueSize,
    unit,
    shape: shape || 'blob',
    measurementMethod: method || 'taille typique / norme documentée (convention de jeu)',
    source: 'Curated Size It catalog',
    license: 'Public Domain / CC0 silhouette (generated)'
  };
}

